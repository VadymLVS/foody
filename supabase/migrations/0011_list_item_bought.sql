--
-- Выполнять в SQL Editor Supabase ПЕРЕД заливкой кода v0.19.
-- Повторный запуск безопасен.
--
-- Что было не так. Внутри списка ползунок — это наличие продукта дома
-- (`products.in_stock`), и «Куплено 4 из 6» просто считало, у скольких позиций
-- стоит наличие. Продукты, которые дома уже есть, объявлялись купленными, и
-- свежесозданный список открывался наполовину отмеченным, хотя человек
-- в магазин ещё не выходил (Vadym, 10-01). Побочно: если дома есть всё,
-- приложение сразу предлагало «Всё куплено · Закрыть список» — закрыть
-- поездку, которая не начиналась.
--
-- Решение Vadym (10-01): отметка в списке значит «куплено» и сразу ставит
-- наличие дома; снятие убирает «куплено» и возвращает наличие как было
-- до поездки. Поэтому две колонки, а не одна:
--   bought       — отметка этой поездки, из неё считается прогресс;
--   stock_before — каким было наличие дома, когда позицию внесли в список.
-- Без второй «вернуть как было» не отличить от «выключить»: брокколи дома
-- были, лука не было, и снятие отметки должно вести себя по-разному.
--
-- Количество при снятии отметки не обнуляется. D-075 обнуляет его, когда
-- ползунок выключают в обычном списке («выключил — значит кончилось»), но
-- здесь снятие означает «не купил», а не «дома нет», и обнуление стёрло бы
-- то, сколько лежало дома до поездки.

begin;

-- Переносим существующие списки в один проход: для уже лежащих позиций
-- «прежнее наличие» берём из продуктов на момент миграции. Это приближение,
-- но куда ближе к правде, чем общий false, с которым снятие отметки у
-- домашнего продукта выключало бы его наличие. Блок срабатывает только при
-- первом прогоне — иначе повторный запуск перезаписал бы живые данные.
do $$
declare v_fresh boolean := false;
begin
  if not exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'product_list_items'
       and column_name = 'stock_before'
  ) then
    v_fresh := true;
  end if;

  alter table product_list_items
    add column if not exists bought       boolean not null default false,
    add column if not exists stock_before boolean not null default false;

  if v_fresh then
    update product_list_items i
       set stock_before = p.in_stock
      from products p
     where p.id = i.product_id;
  end if;
end $$;

-- Прогресс поездки считается по bought, поэтому колонка участвует в выборке
-- на каждом открытии экрана продуктов
create index if not exists product_list_items_bought
  on product_list_items (list_id) where bought;

-- 0010 выдал право на правку только количества. Теперь правятся и отметка,
-- и прежнее наличие. Остальные колонки по-прежнему менять нельзя: подменить
-- продукт в позиции или перевесить её в другой список правами не разрешено.
grant update (quantity, bought, stock_before) on table product_list_items to authenticated;

commit;
