/** Рецепт блюда: свой текст, иначе — из справочника по ключу. */
export function recipeFor(dish: { recipe?: string | null; library_key: string | null }): string | null {
  if (dish.recipe?.trim()) return dish.recipe;
  return (dish.library_key && DISH_RECIPES[dish.library_key]) || null;
}
